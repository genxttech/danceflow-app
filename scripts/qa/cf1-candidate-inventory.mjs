// CF1 app candidate: file-by-file inventory against the live release.
// Usage: node scripts/qa/cf1-candidate-inventory.mjs <live-base> <int5-tip> <int5-base> <hotfix> <out.md> <out.json>
// Every path changed between <live-base> and HEAD is classified, plus every int5 path that is deliberately not carried.
import fs from "node:fs";
import { execFileSync } from "node:child_process";

const [base, int5, int5Base, hotfix, outMd, outJson] = process.argv.slice(2);
const git = (...args) => execFileSync("git", args, { encoding: "utf8", maxBuffer: 64 << 20 });
const lines = (s) => s.split(/\r?\n/).filter(Boolean);

const candidate = lines(git("diff", "--name-status", base, "HEAD")).map((l) => { const [s, ...p] = l.split("\t"); return { status: s, path: p.at(-1) }; });
const sameAsInt5 = new Set(lines(git("ls-tree", "-r", "--name-only", int5)));
const differsFromInt5 = new Set(lines(git("diff", "--name-only", int5, "HEAD")));
const hotfixFiles = new Set(lines(git("diff", "--name-only", base, hotfix)));
const int5Changed = lines(git("diff", "--name-status", int5Base, int5)).map((l) => { const [s, ...p] = l.split("\t"); return { status: s, path: p.at(-1) }; });

const int5Paths = new Set(int5Changed.map((c) => c.path));

function area(p) {
  if (p.startsWith("src/lib/supabase/migrations/rollback/")) return "migration rollback (Git-only copy)";
  if (p.startsWith("src/lib/supabase/migrations/sql-tests/")) return "SQL test";
  if (p.startsWith("src/lib/supabase/migrations/")) return "migration (Git-only copy)";
  if (/__tests__|\.test\.ts$/.test(p)) return "unit test";
  if (p.startsWith("e2e/")) return "e2e harness";
  if (p.startsWith("docs/")) return "docs";
  if (p.startsWith("scripts/")) return "QA script";
  if (p.startsWith("src/app/")) return "app route/page/action";
  return "library";
}
function origin(p) {
  if (hotfixFiles.has(p)) return `hotfix ${hotfix.slice(0, 8)} (+ candidate gate edits)`;
  if (!sameAsInt5.has(p)) return "new in this candidate";
  if (!int5Paths.has(p)) return "live release file, edited here (dark gate)";
  return differsFromInt5.has(p) ? `int5 ${int5.slice(0, 8)}, edited here` : `int5 ${int5.slice(0, 8)}, byte-identical`;
}
const rows = candidate.map((c) => ({ ...c, change: c.status === "A" ? "added" : c.status === "M" ? "changed" : c.status === "D" ? "removed" : c.status, area: area(c.path), origin: origin(c.path) }));

const carried = new Set(candidate.map((c) => c.path));
const reasons = [
  [/^docs\/twilio\//, "TW-4F docs: int5 only scrubbed local paths; TW-4F files are preserved byte-for-byte from the live release"],
  [/^src\/lib\/competition\/__tests__\/(render|workspace)\.phase10b\.test\.ts$/, "kept at the live version: int5 changed them to expect the CF1 navigation unconditionally; the dark default keeps the live navigation (flag-on navigation is asserted in finalsGate.cf1dark.test.ts)"],
  [/^package\.json$/, "main-only qa:billing-* scripts (not part of the live release); no dependency change"],
  [/^docs\/qa\/cf1-rb4-int5\/(evidence_composed_nor2_e84d535b\.txt|evidence_final_order_r2_gate\.txt|rb4_int5\.sh)$/, "RB4 evidence carrying local machine paths (fails the qaHarnessPins guard); kept on cf1/integration-5"],
];
const excluded = int5Changed.filter((c) => !carried.has(c.path) || c.path === "e2e/README.md").map((c) => {
  if (c.path === "e2e/README.md") return { path: c.path, status: c.status, reason: "carried as a 3-way merge of the int5 hunk onto the live README (not the int5 file), so it differs from int5" };
  const hit = reasons.find(([re]) => re.test(c.path));
  return { path: c.path, status: c.status, reason: hit ? hit[1] : "UNCLASSIFIED" };
});

const count = (k) => rows.reduce((m, r) => ((m[r[k]] = (m[r[k]] ?? 0) + 1), m), {});
const summary = { base, int5, hotfix, files: rows.length, byChange: count("change"), byArea: count("area"), byOrigin: count("origin"), excluded: excluded.length };
fs.writeFileSync(outJson, JSON.stringify({ summary, files: rows, excluded }, null, 2) + "\n");

const md = [];
md.push(`# CF1 app candidate: file inventory`, "");
md.push(`Generated by \`scripts/qa/cf1-candidate-inventory.mjs\` against live release \`${base}\`, int5 tip \`${int5}\`, heat-size hotfix \`${hotfix}\`.`, "");
md.push(`**${rows.length} paths** differ from the live release. By change: ${Object.entries(summary.byChange).map(([k, v]) => `${k} ${v}`).join(", ")}.`, "");
md.push("| Area | Files |", "|---|---|", ...Object.entries(summary.byArea).map(([k, v]) => `| ${k} | ${v} |`), "");
md.push("| Origin | Files |", "|---|---|", ...Object.entries(summary.byOrigin).map(([k, v]) => `| ${k} | ${v} |`), "");
md.push("## Deliberately excluded from cf1/integration-5", "", "| Path | int5 change | Reason |", "|---|---|---|", ...excluded.map((e) => `| \`${e.path}\` | ${e.status} | ${e.reason} |`), "");
md.push("Also not carried: every change on `main` after the live base (the candidate is the live release plus the CF1 overlay, never main).", "");
md.push("## All files", "", "| Change | Area | Origin | Path |", "|---|---|---|---|", ...rows.map((r) => `| ${r.change} | ${r.area} | ${r.origin} | \`${r.path}\` |`), "");
fs.writeFileSync(outMd, md.join("\n"));
console.log(JSON.stringify(summary, null, 1));
if (excluded.some((e) => e.reason === "UNCLASSIFIED")) { console.error("UNCLASSIFIED exclusions:", excluded.filter((e) => e.reason === "UNCLASSIFIED").map((e) => e.path)); process.exit(2); }
