import { NextResponse } from "next/server";
import { canEditClients, canViewClients } from "@/lib/auth/permissions";
import { normalizeStudentApiUuid } from "@/lib/auth/studentApiAuth";
import { requireStaffApi, staffApiError, staffApiJson, staffApiUnavailable } from "@/lib/auth/staffApiAuth";
import { addClientActivityNote, decodeNoteCursor, listClientNotes, validateClientNoteInput } from "@/lib/staff/clientNotes";
import { requireStaffWrite } from "@/lib/staff/writeGuard";
import { readEntityId, readIdempotencyKey, readJsonBody, staffConflict, staffWriteError } from "@/lib/staff/writeSupport";

/** API-only cap; the web form has none. */
const MAX_NOTE_LENGTH = 5000;

/**
 * Idempotency: CLIENT-SUPPLIED ENTITY ID (Staff API write helpers). The app sends `noteId`, a UUID it generated once for this user action, and resends
 * the same value on every retry. See docs/mobile/Staff_API_Contract.md.
 */
export async function POST(request: Request, { params }: { params: Promise<{ studioId: string; clientId: string }> }) {
  const { studioId, clientId } = await params;
  const guard = await requireStaffWrite(request, studioId, "clientNotes");
  if (!guard.ok) return guard.response;

  // Same roles as the web "add note" action (canEditClients): owners, admins and front desk. Instructors are refused.
  if (!canEditClients(guard.studioRole)) {
    return staffApiError("role_not_permitted", "Your role cannot add client notes.", 403);
  }

  const normalizedClientId = normalizeStudentApiUuid(clientId);
  if (!normalizedClientId) return staffWriteError("invalid_request", "A valid client id is required.", 400);

  const key = readIdempotencyKey(request);
  if (!key.ok) return key.response;

  const parsedBody = await readJsonBody(request);
  if (!parsedBody.ok) return parsedBody.response;
  const payload = parsedBody.body;

  const noteId = readEntityId(payload.noteId);
  if (!noteId) return staffWriteError("invalid_request", "noteId must be a UUID generated by the app for this note (reuse it on retries).", 400);

  const text = (value: unknown) => (typeof value === "string" ? value.trim() : "");
  for (const field of ["noteType", "body", "occurredAt"] as const) {
    if (payload[field] !== undefined && payload[field] !== null && typeof payload[field] !== "string") {
      return staffWriteError("invalid_request", `${field} must be a string.`, 400);
    }
  }
  const body = text(payload.body);
  if (body.length > MAX_NOTE_LENGTH) {
    return staffWriteError("invalid_request", `body must be at most ${MAX_NOTE_LENGTH} characters.`, 400);
  }

  const parsed = validateClientNoteInput({
    clientId: normalizedClientId,
    noteType: text(payload.noteType),
    body,
    occurredAt: text(payload.occurredAt),
  });
  if (!parsed.ok) {
    return staffWriteError(
      "invalid_request",
      parsed.reason === "missing_fields"
        ? "body is required."
        : parsed.reason === "invalid_type"
          ? "noteType is not one of general, follow_up, sales, lesson, billing, concern."
          : "occurredAt must be an ISO 8601 date-time.",
      400,
    );
  }

  try {
    const result = await addClientActivityNote({
      supabase: guard.supabase,
      studioId: guard.studioId,
      clientId: normalizedClientId.toLowerCase(),
      userId: guard.user.id,
      input: parsed.input,
      noteId,
    });

    if (!result.ok) {
      if (result.reason === "client_not_found") return staffApiError("not_found", "Client not found.", 404);
      if (result.reason === "idempotency_conflict") {
        return staffConflict(
          "idempotency_conflict",
          "This noteId was already used for a different note.",
          result.current ? { note: result.current } : null,
        );
      }
      throw new Error("Client note save failed.");
    }

    // staffApiJson always answers 200 (and lives under src/lib/auth, owner-gated), so the 201 is built here with the same headers.
    const ok = staffApiJson({ note: result.note });
    return result.created ? NextResponse.json({ note: result.note }, { status: 201, headers: ok.headers }) : ok;
  } catch (failure) {
    return staffApiUnavailable(new URL(request.url).pathname, failure);
  }
}

const DEFAULT_LIMIT = 25;
const MAX_LIMIT = 50;

/**
 * The client's notes, newest first (what the web client page shows). Reads are not behind the write guard. Roles: canViewClients (owner, admin,
 * front desk); instructors cannot read client records, so they cannot read notes either.
 */
export async function GET(request: Request, { params }: { params: Promise<{ studioId: string; clientId: string }> }) {
  const { studioId, clientId } = await params;
  const guard = await requireStaffApi(request, studioId);
  if (!guard.ok) return guard.response;

  if (!canViewClients(guard.studioRole)) {
    return staffApiError("role_not_permitted", "Your role cannot read client notes.", 403);
  }

  const normalizedClientId = normalizeStudentApiUuid(clientId);
  if (!normalizedClientId) return staffApiError("invalid_request", "A valid client id is required.", 400);

  const url = new URL(request.url);
  const rawLimit = url.searchParams.get("limit");
  const limit = rawLimit === null ? DEFAULT_LIMIT : Number(rawLimit);
  if (!Number.isInteger(limit) || limit < 1 || limit > MAX_LIMIT) {
    return staffApiError("invalid_request", `limit must be an integer from 1 to ${MAX_LIMIT}.`, 400);
  }
  const cursor = decodeNoteCursor(url.searchParams.get("cursor"));
  if (cursor === "invalid") return staffApiError("invalid_request", "cursor is not valid.", 400);

  try {
    const result = await listClientNotes({
      supabase: guard.supabase,
      studioId: guard.studioId,
      clientId: normalizedClientId.toLowerCase(),
      cursor,
      limit,
    });
    if (!result) return staffApiError("not_found", "Client not found.", 404);
    return staffApiJson(result);
  } catch (failure) {
    return staffApiUnavailable(url.pathname, failure);
  }
}
